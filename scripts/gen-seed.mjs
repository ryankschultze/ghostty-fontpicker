#!/usr/bin/env node
// Regenerates Sources/FontPickerCore/SeedCatalog.swift from the specimen page.
//
// The page carries hand-written knowledge the app can't measure: display names, the
// grouping, the one-paragraph note per family, which italics are cursive, and which
// stylistic sets are worth switching on by default. Everything measurable (features,
// ligatures, metrics, weights) is probed from the installed fonts at runtime instead.
//
// The page embeds the fonts it shows, so it is not in the repo. Keep a copy beside the
// README, where git ignores it, or pass its path:
//
//   node scripts/gen-seed.mjs [path/to/specimens.html]

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = process.argv[2] ?? join(root, "Nerd Font Specimens.html");
const out = join(root, "Sources/FontPickerCore/SeedCatalog.swift");

if (!existsSync(src)) {
  console.error(`gen-seed: ${src} not found. The specimen page is not in the repo; pass the path to a copy.`);
  process.exit(1);
}

const line = readFileSync(src, "utf8").split("\n").find((l) => l.startsWith("const DATA = "));
if (!line) throw new Error(`no "const DATA = " line in ${src}`);
const data = JSON.parse(line.replace(/^const DATA = /, "").replace(/;\s*$/, ""));

const entries = data.fams.map((f) => ({
  family: f.family,
  short: f.short,
  group: f.group,
  note: f.note,
  cursive: f.cursive,
  preset: f.preset,
}));

const json = JSON.stringify(entries, null, 1);
if (json.includes('"""#')) throw new Error("seed JSON would terminate the Swift raw string");

writeFileSync(
  out,
  `// Generated by scripts/gen-seed.mjs from the specimen page. Do not edit by hand.
import Foundation

/// Curated facts about a family that can't be measured from the font files.
struct SeedEntry: Decodable {
    let family: String
    let short: String
    let group: String
    let note: String
    let cursive: Bool
    let preset: [String]
}

enum SeedCatalog {
    /// Entries in the curated display order.
    static let entries: [SeedEntry] = {
        // The literal below is generated, so a decode failure is a build-time mistake.
        try! JSONDecoder().decode([SeedEntry].self, from: Data(json.utf8))
    }()

    /// Family name to its position in \`entries\`.
    static let index: [String: Int] = Dictionary(
        uniqueKeysWithValues: entries.enumerated().map { ($0.element.family, $0.offset) })

    static func entry(for family: String) -> SeedEntry? {
        index[family].map { entries[$0] }
    }

    private static let json = #"""
${json}
"""#
}
`,
);
console.log(`wrote ${out} (${entries.length} families)`);
